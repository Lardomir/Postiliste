const fs = require("node:fs");
const path = require("node:path");
const { Pool } = require("pg");
const { tokenHash } = require("./security");

class Store {
  constructor(options = {}) {
    this.postgres = Boolean(options.databaseUrl || process.env.DATABASE_URL);
    if (this.postgres) {
      this.pool = new Pool({
        connectionString: options.databaseUrl || process.env.DATABASE_URL,
      });
    } else {
      const filename =
        options.dbPath ||
        process.env.DB_PATH ||
        path.join(__dirname, "..", "data", "postiliste.db");
      if (filename !== ":memory:")
        fs.mkdirSync(path.dirname(filename), { recursive: true });
      const sqlite3 = require("sqlite3");
      this.db = new sqlite3.Database(filename);
    }
    this.ready = this.migrate();
  }

  placeholders(sql) {
    let index = 0;
    return this.postgres ? sql.replace(/\?/g, () => "$" + ++index) : sql;
  }

  async directAll(sql, params = []) {
    if (this.postgres) {
      const result = await this.pool.query(this.placeholders(sql), params);
      return result.rows;
    }
    return new Promise((resolve, reject) =>
      this.db.all(sql, params, (error, rows) =>
        error ? reject(error) : resolve(rows),
      ),
    );
  }

  async directRun(sql, params = []) {
    if (this.postgres) {
      const result = await this.pool.query(this.placeholders(sql), params);
      return { changes: result.rowCount, id: result.rows[0]?.id };
    }
    return new Promise((resolve, reject) =>
      this.db.run(sql, params, function onRun(error) {
        return error
          ? reject(error)
          : resolve({ changes: this.changes, id: this.lastID });
      }),
    );
  }

  async directExec(sql) {
    if (this.postgres) return this.pool.query(sql);
    return new Promise((resolve, reject) =>
      this.db.exec(sql, (error) => (error ? reject(error) : resolve())),
    );
  }

  async migrate() {
    if (!this.postgres) await this.directExec("PRAGMA foreign_keys = ON;");
    await this.directExec(
      "CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY);",
    );
    const rows = await this.directAll(
      "SELECT version FROM schema_migrations WHERE version = 3",
    );
    if (rows.length) return;

    const id = this.postgres
      ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
      : "INTEGER PRIMARY KEY AUTOINCREMENT";
    const migrations = [
      `CREATE TABLE IF NOT EXISTS users (
        id ${id}, username TEXT NOT NULL UNIQUE, email TEXT,
        password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK (role IN ('ADMIN', 'USER')),
        created_at TEXT NOT NULL, last_login_at TEXT
      )`,
      `CREATE TABLE IF NOT EXISTS shopping_lists (
        id ${id}, title TEXT NOT NULL, due_date TEXT, responsible_user_id INTEGER NOT NULL
          REFERENCES users(id) ON DELETE RESTRICT,
        completed INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL, updated_at TEXT NOT NULL
      )`,
      `CREATE TABLE IF NOT EXISTS list_members (
        list_id INTEGER NOT NULL REFERENCES shopping_lists(id) ON DELETE CASCADE,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        PRIMARY KEY (list_id, user_id)
      )`,
      `CREATE TABLE IF NOT EXISTS list_items (
        id ${id}, list_id INTEGER NOT NULL REFERENCES shopping_lists(id) ON DELETE CASCADE,
        name TEXT NOT NULL, quantity TEXT, purchased INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL
      )`,
      `CREATE TABLE IF NOT EXISTS sessions (
        id_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        expires_at INTEGER NOT NULL
      )`,
      "CREATE INDEX IF NOT EXISTS list_items_by_list ON list_items (list_id)",
      "CREATE INDEX IF NOT EXISTS list_members_by_user ON list_members (user_id)",
    ];
    for (const sql of migrations) await this.directExec(sql);
    await this.directRun("INSERT INTO schema_migrations(version) VALUES (3)");
  }

  async all(sql, params = []) {
    await this.ready;
    return this.directAll(sql, params);
  }
  async one(sql, params = []) {
    const rows = await this.all(sql, params);
    return rows[0] || null;
  }
  async run(sql, params = []) {
    await this.ready;
    return this.directRun(sql, params);
  }
  async insert(sql, params = []) {
    await this.ready;
    if (this.postgres) {
      const result = await this.directAll(sql + " RETURNING id", params);
      return result[0].id;
    }
    const result = await this.directRun(sql, params);
    return result.id;
  }

  // Application users and short-lived server-side sessions.
  users() {
    return this.all(
      "SELECT id, username, email, role, created_at, last_login_at FROM users ORDER BY username",
    );
  }
  findUserByName(name) {
    return this.one("SELECT * FROM users WHERE username = ?", [name]);
  }
  findUser(id) {
    return this.one(
      "SELECT id, username, email, role, created_at, last_login_at FROM users WHERE id = ?",
      [id],
    );
  }
  userCount() {
    return this.one("SELECT COUNT(*) AS total FROM users");
  }
  createUser(name, mail, hash, role = "USER") {
    return this.insert(
      "INSERT INTO users(username,email,password_hash,role,created_at) VALUES(?,?,?,?,?)",
      [name, mail, hash, role, new Date().toISOString()],
    );
  }
  updateUser(id, name, mail, role, passwordHash) {
    return passwordHash
      ? this.run(
          "UPDATE users SET username=?,email=?,role=?,password_hash=? WHERE id=?",
          [name, mail, role, passwordHash, id],
        )
      : this.run("UPDATE users SET username=?,email=?,role=? WHERE id=?", [
          name,
          mail,
          role,
          id,
        ]);
  }
  deleteUser(id) {
    return this.run("DELETE FROM users WHERE id=?", [id]);
  }
  responsibleCount(id) {
    return this.one(
      "SELECT COUNT(*) AS total FROM shopping_lists WHERE responsible_user_id=?",
      [id],
    );
  }
  setLastLogin(id) {
    return this.run("UPDATE users SET last_login_at=? WHERE id=?", [
      new Date().toISOString(),
      id,
    ]);
  }
  createSession(token, userId, until) {
    return this.run(
      "INSERT INTO sessions(id_hash,user_id,expires_at) VALUES(?,?,?)",
      [tokenHash(token), userId, until],
    );
  }
  async sessionUser(token) {
    if (!token || !/^[a-f0-9]{64}$/.test(token)) return null;
    return this.one(
      `SELECT users.id,users.username,users.email,users.role
      FROM sessions JOIN users ON users.id=sessions.user_id
      WHERE sessions.id_hash=? AND sessions.expires_at>?`,
      [tokenHash(token), Math.floor(Date.now() / 1000)],
    );
  }
  revokeSession(token) {
    return this.run("DELETE FROM sessions WHERE id_hash=?", [tokenHash(token)]);
  }

  // Lists are visible only to administrators, members or their responsible user.
  listLists(user) {
    if (user.role === "ADMIN") {
      return this.all(`SELECT l.*,u.username AS responsible_name
        FROM shopping_lists l JOIN users u ON u.id=l.responsible_user_id ORDER BY l.completed,l.id DESC`);
    }
    return this.all(
      `SELECT DISTINCT l.*,u.username AS responsible_name
      FROM shopping_lists l JOIN users u ON u.id=l.responsible_user_id
      LEFT JOIN list_members m ON m.list_id=l.id
      WHERE l.responsible_user_id=? OR m.user_id=? ORDER BY l.completed,l.id DESC`,
      [user.id, user.id],
    );
  }
  async getList(id, user) {
    const row = await this.one(
      `SELECT l.*,u.username AS responsible_name
      FROM shopping_lists l JOIN users u ON u.id=l.responsible_user_id WHERE l.id=?`,
      [id],
    );
    if (!row) return null;
    if (user.role === "ADMIN" || row.responsible_user_id === user.id)
      return row;
    const member = await this.one(
      "SELECT 1 AS member FROM list_members WHERE list_id=? AND user_id=?",
      [id, user.id],
    );
    return member ? row : null;
  }
  members(id) {
    return this.all(
      `SELECT u.id,u.username,u.email FROM users u
    JOIN list_members m ON m.user_id=u.id WHERE m.list_id=? ORDER BY u.username`,
      [id],
    );
  }
  memberIds(id) {
    return this.all("SELECT user_id FROM list_members WHERE list_id=?", [id]);
  }
  items(id) {
    return this.all(
      "SELECT * FROM list_items WHERE list_id=? ORDER BY purchased,id DESC",
      [id],
    );
  }
  async validUsers(ids) {
    if (!ids.length) return true;
    const users = await this.all("SELECT id FROM users");
    const valid = new Set(users.map((user) => user.id));
    return ids.every((id) => valid.has(id));
  }
  async replaceMembers(listId, ids) {
    await this.run("DELETE FROM list_members WHERE list_id=?", [listId]);
    for (const id of [...new Set(ids)]) {
      await this.run("INSERT INTO list_members(list_id,user_id) VALUES(?,?)", [
        listId,
        id,
      ]);
    }
  }
  async createList(data) {
    const timestamp = new Date().toISOString();
    const id = await this.insert(
      `INSERT INTO shopping_lists
      (title,due_date,responsible_user_id,completed,created_at,updated_at)
      VALUES(?,?,?,0,?,?)`,
      [data.title, data.dueDate, data.responsibleUserId, timestamp, timestamp],
    );
    await this.replaceMembers(id, data.memberIds);
    return id;
  }
  async updateList(id, data) {
    await this.run(
      `UPDATE shopping_lists SET title=?,due_date=?,responsible_user_id=?,updated_at=? WHERE id=?`,
      [
        data.title,
        data.dueDate,
        data.responsibleUserId,
        new Date().toISOString(),
        id,
      ],
    );
    await this.replaceMembers(id, data.memberIds);
  }
  toggleList(id) {
    return this.run(
      "UPDATE shopping_lists SET completed=1-completed,updated_at=? WHERE id=?",
      [new Date().toISOString(), id],
    );
  }
  deleteList(id) {
    return this.run("DELETE FROM shopping_lists WHERE id=?", [id]);
  }
  addItem(listId, name, quantity) {
    return this.insert(
      "INSERT INTO list_items(list_id,name,quantity,created_at) VALUES(?,?,?,?)",
      [listId, name, quantity, new Date().toISOString()],
    );
  }
  toggleItem(listId, itemId) {
    return this.run(
      "UPDATE list_items SET purchased=1-purchased WHERE list_id=? AND id=?",
      [listId, itemId],
    );
  }
  deleteItem(listId, itemId) {
    return this.run("DELETE FROM list_items WHERE list_id=? AND id=?", [
      listId,
      itemId,
    ]);
  }

  async close() {
    await this.ready;
    if (this.postgres) return this.pool.end();
    return new Promise((resolve, reject) =>
      this.db.close((error) => (error ? reject(error) : resolve())),
    );
  }
}

module.exports = Store;
